export const journeyEvent = (id: string | null | undefined) => journeyEvents.find(event => event.id === id);
export const journeyEra = (id: string | null | undefined) => journeyEras.find(era => era.id === id);
export const quickJourneyIds = ['east-zhou', 'qin-unifies', 'han-founded', 'eastern-han', 'red-cliffs', 'jin-unifies', 'eastern-jin', 'liu-song', 'sui-unifies', 'an-lushan', 'five-dynasties', 'jingkang', 'yuan-unifies', 'ming-founded', 'ming-falls'];
export function journeyUrl(eventId = '', eraId = '', base = location.href, scope = 'quick'): string {
  const url = new URL(base); url.search = ''; url.hash = '';
  url.searchParams.set('journey', journeyEvent(eventId)?.id ?? '');
  if (!eventId && journeyEra(eraId)) url.searchParams.set('era', eraId);
  if (scope === 'all') url.searchParams.set('scope', 'all');
  return url.href;
}
export function journeySourceUrl(event: JourneyEvent, source: JourneySource, base = location.href): string {
  const url = new URL(journeyUrl(event.id, '', base, new URL(base).searchParams.get('scope') ?? 'quick'));
  if (source.book === 'shiji') url.hash = `shiji/${source.volume}/${source.block}`;
  else {
    url.search = ''; url.searchParams.set('library', source.book);
    url.searchParams.set('volume', String(source.volume)); url.searchParams.set('from', event.id); url.hash = source.block;
    if (new URL(base).searchParams.get('scope') === 'all') url.searchParams.set('scope', 'all');
  }
  return url.href;
}
export function sourceJourney(href: string) {
  const url = new URL(href); const event = journeyEvent(url.searchParams.get('from'));
  const source = event?.sources.find(source => source.book === url.searchParams.get('library') && String(source.volume) === url.searchParams.get('volume') && `#${source.block}` === url.hash);
  return event && source ? { event, source } : null;
}
