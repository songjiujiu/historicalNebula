export const modernEraGuides = modernJourneyEras.map(era => ({ ...era, ...eraReading[era.id] }));
export const modernEventGuides = modernChapters.map(chapter => {
  const event = modernJourneyEvents.find(e => e.id === chapter.id)!;
  const [question, ...pointers] = readingPrompts[chapter.id];
  return { ...event, question, chapter, sections: chapter.outline.map((s, index) => ({ ...s, pointer: pointers[index] })) };
});
export const modernEventGuide = (id: string) => modernEventGuides.find(g => g.id === id);
