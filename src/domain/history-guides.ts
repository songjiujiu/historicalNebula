export const historyBookGuide = (id: string | null | undefined) => historyBookGuides.find(item => item.book === id);
export function historyGuideSteps(book: string) {
  return journeyEvents.filter(event => event.sources.some(source => source.book === book)).map(event => ({
    event, sources: event.sources.filter(source => source.book === book),
  }));
}
export interface HistoryGuideLocation { book: string; step: string }
export function historyGuideLocation(href: string): HistoryGuideLocation {
  const params = new URL(href).searchParams;
  const book = historyBookGuide(params.get('histories'))?.book ?? '';
  const steps = historyGuideSteps(book);
  return { book, step: steps.find(item => item.event.id === params.get('step'))?.event.id ?? steps[0]?.event.id ?? '' };
}
export function historyGuideUrl(book = '', step = '', base = location.href) {
  const url = new URL(base); url.search = ''; url.hash = ''; url.username = ''; url.password = '';
  url.searchParams.set('histories', historyBookGuide(book)?.book ?? '');
  if (historyGuideSteps(book).some(item => item.event.id === step)) url.searchParams.set('step', step);
  return url.href;
}
export function historyGuideSourceUrl(book: string, step: string, source: JourneySource, base = location.href) {
  const selected = historyGuideSteps(book).find(item => item.event.id === step);
  if (!selected?.sources.some(item => item.volume === source.volume && item.block === source.block && item.book === source.book)) return historyGuideUrl(book, step, base);
  const url = new URL(base); url.search = ''; url.hash = source.block; url.username = ''; url.password = '';
  url.searchParams.set('library', book); url.searchParams.set('volume', String(source.volume)); url.searchParams.set('guide', step);
  return url.href;
}
/** Only attach a return link / quotation when the book, volume and paragraph all match. */
export function sourceHistoryGuide(href: string) {
  const url = new URL(href), book = url.searchParams.get('library') ?? '';
  if (!historyBookGuide(book)) return null;
  const selected = historyGuideSteps(book).find(item => item.event.id === url.searchParams.get('guide'));
  const source = selected?.sources.find(item => String(item.volume) === url.searchParams.get('volume') && `#${item.block}` === url.hash);
  return selected && source ? { book, event: selected.event, source } : null;
}
